/*
 * rt - 7th Level engine runtime for the game logic translated to C (port\game\*.c).
 *
 * The files in port\game\ were generated once by port\tools\scr2c.c from the scripts of the
 * .BIN files and are now maintained as sources: each script is a native C function. This module
 * is the portable C rewrite of the original engine (TOPSY.EXE) functions that those scripts
 * call: resources, libraries, timers, builtin functions, strings.
 *
 * Variables: globals G(0..5117) (encoding < 0x13FE). G(0..5000) belong to the library and are
 * saved when the library changes (FUN_1008_C282); G(5001..5117) (DS:3C5C, 0x75 words) are
 * shared by all libraries: zeroed once at startup, the first 16 are system variables
 * written by the engine (FUN_1008_BF32, see rt_open_library). Locals live in frames (l[n]);
 * a call with frame F passes l + F to the callee, as the original shifted DAT_10C2 by F words.
 */
#ifndef RT_H
#define RT_H

#include <stdint.h>
#include <stdio.h>

#include "lb7.h"

#define RT_NGLOBALS   0x13FE /* 5118 */
#define RT_GSHARED    5001   /* first global shared by all libraries */
#define RT_LSTACK     4096   /* words for the local-variable frames */
#define RT_MAX_DEPTH  30     /* same as the original (error 0x6A) */

typedef struct Rt Rt;
typedef void (*RtScript)(Rt *rt, int16_t *l);
typedef int (*RtList)(Rt *rt, int16_t *l, unsigned item); /* 0 = the calling script ends */
/* Animation events (type 15, command 0x15): off = offset of the command within the animation. */
typedef int (*RtAnimEvent)(Rt *rt, unsigned off);

/* Translated logic of a .BIN archive (generated by scr2c). */
typedef struct {
	const char *file;          /* e.g. "TOPSMAIN.BIN" */
	uint32_t n_entries;
	const RtScript *scripts;   /* per entry: script function or NULL */
	const RtList *lists;       /* per entry: list function (type 11) or NULL */
	const uint16_t *list_len;  /* per entry: number of instructions in the list */
	const RtAnimEvent *anim_events; /* per entry: animation events (type 15) or NULL */
} RtLib;

/* Runs the event at offset off of animation id (called by the animation engine). */
int rt_anim_event(Rt *rt, unsigned id, unsigned off);
/* Animation command 0x16 {script, n, encoded arguments} of the sprite (FUN_1008_CC14). */
void rt_anim_call(Rt *rt, unsigned sprite, const uint8_t *cmd);

/* Rectangular clickable area (opcode 04 with sprite 0, 13-byte record at DS:56FB). The
 * coordinates are relative to the screen center; script and argument are encoded operands. */
#define RT_MAX_HOTSPOTS 256
typedef struct {
	int16_t x1, y1, x2, y2;
	uint16_t script, arg;
	uint8_t off;               /* +0x0C: disabled */
} RtHotspot;

/* Input fields of the type 17 resource loaded in memory (entry data, TOPSY
 * FUN_1008_73DC): +0 click script, +2 argument, +8 drag-start script, +0xA
 * release script, +0x10 click disabled, +0x13 draggable. Initial values from the file. */
typedef struct {
	uint16_t click, click_arg, drag, drop;
	uint8_t click_off, draggable, loaded;
} RtObj;

struct Rt {
	/* current library */
	const RtLib *code;
	Lb7 lib;
	int16_t *g;                /* globals of the current library */
	char (*str)[128];          /* string variables of the current library */
	uint16_t n_str;
	/* execution */
	int16_t lstack[RT_LSTACK];
	int16_t retval;            /* DAT_40DA */
	int depth;                 /* DAT_153C */
	int stop;                  /* DAT_1548 */
	uint32_t rand_seed;
	/* engine state set by the scripts (meaning to be completed, see OPCODE_SCRIPT.md) */
	int16_t v1502, v1504, v1506, v1508, v150e, v40dc, v40de;
	int16_t table4090[0x22];
	char str5bd8[17];
	int cursor_mode;           /* DAT_1514 */
	int fade_pending;          /* DAT_5B75: fade in when the library opens */
	int faded;                 /* DAT_5B6D: screen off (yes at startup) */
	int fade_level;            /* 0..256: brightness of colors 10..245 (S_021) */
	/* draws and presents a frame (S_001): provided by whoever owns the window; NULL = nothing */
	void (*frame)(struct Rt *rt);
	int in_startup;            /* DAT_5B8D: library startup script running */
	char ini_path[512];        /* the port's 7THLEVEL.INI (default: current folder) */
	/* requests to the main loop */
	char link_file[17];
	int link_stop_audio, link_return;
	int link_pending;
	int quit;
	/* opcode 1E: deferred calls {script, arg1, arg2} (encoded operands), queue of 40 records
	   at DS:5893 run by the main loop (TOPSY 1010:25B8, 1008:4288 -> 1008:CDAC) */
	uint16_t evq[40][3];
	int evq_n;
	uint16_t timer_script;
	uint16_t timer_ms;         /* builtin 93: interval (DAT_10E4, word: a[1]*1000 wraps around) */
	uint8_t mute;              /* opcode 35: global mute (A_023, audio DLL state) */
	uint8_t joy_swap;          /* builtin 82: joysticks 1 and 2 swapped (DAT_5B7F) */
	/* pause and focus (FUN_1008_3140, FUN_1008_E896): the engine works only if !paused && active */
	uint8_t paused;            /* DAT_5B85: Pause key */
	uint8_t active;            /* DAT_5B6A: window active (changes only with AltTab=0) */
	uint8_t active_audio;      /* DAT_5B6B: audio and controllers active */
	/* DS:5B98: engine section of 7THLEVEL.INI, EXE string 0xD2 (LoadString in
	   FUN_1000_05E4): "Topsy Turvy", "Pumbaa And Timon's Jungle Arcade"; set by main.c */
	char app_section[64];
	/* 1 = strings read from the INI (opcode 3B) are kept as they are: the Jungle EXE (1008:AC00)
	   copies them without removing the escapes \n \" \r \t \\ (GAME_INI_NO_UNESCAPE in game.h) */
	uint8_t ini_raw;
	/* 7THLEVEL.INI keys read by the engine at startup, section app_section (rt_load_settings) */
	uint8_t alt_tab, debug, lomem, bg640;
	int max_joy;               /* MaxJoySticks (default 2) */
	uint32_t timer_due_ms;
	/* opcode 13: named timers, at most 20 (14-byte records at DS:5713, error 0x74),
	   checked by the main loop (1008:DED8) */
	struct {
		uint32_t due, interval;
		uint16_t id;           /* raw word of the instruction */
		uint16_t script;       /* encoded operand */
		uint8_t repeat;
	} timers[20];
	int n_timers;
	int timers_paused;         /* builtin 6D (DAT_5B87): timers do not fire */
	uint32_t timers_paused_at;
	/* opcode 21: sprite pairs to check for collisions on every tick (DS:5707,
	   14-byte records, FUN_1008_3E62 / 4124) */
	struct {
		uint16_t a, b;             /* sprite (a < b) */
		uint16_t script, arg1, arg2; /* operands encoded as constants */
		uint8_t repeat, hide_a, hide_b;
	} hits[64];
	int n_hits;
	uint16_t last_rand2e;      /* DAT_0CFA: last offset of opcode 2E */
	/* ---- sound events (opcode 08/0F wave, 50/51 MIDI; TOPSYA01). When a sound ends the DLL sends
	   0x52C {wave/MIDI, script} to the window: script != 0 goes into the deferred-call queue
	   with the sound as argument, script 0 = the sound is unloaded. The end is computed
	   from the duration, like FUN_1000_37EE, so it also works without an audio device. */
	struct RtSound {
		uint16_t res;          /* index entry, 0 = free slot */
		uint16_t script;       /* encoded operand of the end-of-sound script */
		uint8_t notify;        /* "notify at end of sound" flag */
		int voice;             /* mixer entry (wave) */
		uint32_t end_ms;       /* 0 = never ends (repeated forever) */
	} snd[16], music;
	int waves_paused, midi_paused;  /* builtin 70 / counter of builtin 99 (A_025) */
	uint32_t waves_paused_at, midi_paused_at;
	int vol_wave, vol_midi;    /* opcode 5D: device levels 0..31 (>> 11 of Windows) */
	uint32_t now_ms;           /* last time passed to rt_tick */
	int screen_w, screen_h;    /* resolution: G(5003)/G(5004) (default 640x480) */
	int mouse_x, mouse_y;      /* G(5005)/G(5006), relative to the screen center */
	/* ---- input (TOPSY 1008:345C..3CEA, see OPCODE_SCRIPT.md "Input") */
	/* opcode 0C: key (Windows virtual code) -> script; [0] normal, [1] Shift, [2] Ctrl,
	   [3] release; table of 256 11-byte records at DS:4BFB */
	uint16_t key_script[256][4];
	uint8_t key_off[256];
	/* text field (opcode 36, DAT_1500 / record of FUN_1010_217A): text of a type 18 resource
	   edited with WM_CHAR, "_" cursor at the end; text_id = 0: no active field */
	uint16_t text_id, text_var, text_script;
	uint8_t text_max, text_digits;
	char text_buf[132], text_backup[132]; /* text_backup = DS:5C4A */
	int text_flush;            /* request to the loop: flush the queued characters (FUN_1010_2658) */
	uint8_t key_down[256];     /* GetKeyState: keys pressed (opcode 2F, builtin 2F) */
	RtHotspot hot[RT_MAX_HOTSPOTS];
	int n_hot;
	/* opcode 3D: cursor hot zones, at most 40 (0x12-byte records at DS:492B,
	   counter DAT_151E); scripts and arguments encoded as constants, sprite 0 = rectangle */
	struct {
		int16_t x1, y1, x2, y2;
		uint16_t enter, enter_arg, leave, leave_arg;
		uint16_t sprite;       /* decoded id */
	} zones[40];
	int n_zones;
	int zone_cur;              /* DAT_1538: zone under the cursor + 1, 0 = none */
	RtObj *obj;                /* per index entry (type 17 only) */
	uint32_t n_obj;
	uint16_t hover_script;     /* DAT_1542 (builtin 6F): script for entering/leaving sprites */
	uint16_t hover_sprite;     /* DAT_1544: sprite under the cursor (encoded) */
	uint16_t drag_sprite;      /* DAT_14FE: sprite being dragged (encoded), 0 = none */
	int drag_x, drag_y;        /* DAT_10C4/10C6: last position during the drag */
	int warp_mouse;            /* opcode 49: the main loop must move the cursor */
	/* ---- player controllers (TOPSY 1008:4DE8..5DFC, OPCODE_SCRIPT.md "Controller"):
	   two 0x201-byte records at DS:44EA; only the fields used by the games here */
	struct RtPad {
		uint16_t hist;         /* +0: code history, h = h * 16 + code (FUN_1008_4DE8) */
		uint8_t dir;           /* +2: current direction (0 = idle, 3..0x0C) */
		uint8_t buttons;       /* +4: buttons pressed (1, 2, 4, 8) */
		uint16_t script;       /* +6: event script (opcode 54, encoded constant) */
		uint16_t n_seq, n_combo; /* +8 / +0xA: entries of the two tables below */
		/* 9-byte entries {key, script, pattern, mask, enabled} (raw operand words):
		   +0xC opcode 52 table (50 entries), +0x1CE opcode 56 table (4 entries) */
		struct RtPadEntry { uint16_t key, script, pattern, mask; uint8_t enabled; } seq[50], combo[4];
		struct RtPadEntry pending; /* +0x1F2: combo held back by the latch (opcode 55) */
		uint8_t type;          /* +0x1FB: 0 none, 1 joystick, 2 keyboard, 5 mouse */
		uint8_t mirror;        /* +0x1FC: opcode 57, direction codes through DS:0022 */
		uint8_t latch;         /* +0x1FD: opcode 55 */
		uint8_t src;           /* +0x1FF: source (1/2 key sets, 3/4 joystick, 5 mouse) */
		uint8_t active;        /* +0x200 */
		uint8_t hist_on;       /* timer FUN_1008_4C9E armed (id = player + 2) */
		uint32_t hist_due;
	} pad[2];
	uint16_t pad_timeout;      /* DAT_4929: [Input] Timeout of 7THLEVEL.INI (default 200 ms) */
	uint8_t pad_map[8];        /* DS:48FD: source -> player */
	uint8_t keyset[2][16];     /* DS:0042: {key, code} pairs of the two sets (builtin 6B) */
	struct { uint8_t set, ready, code; } padkey[256]; /* DS:40EA: key -> set and code */
	uint8_t pad_state[2];      /* DS:4903: directions pressed per set (bit 1 up, 2 down, 4 right, 8 left) */
	uint8_t pad_rel_on[2];     /* timer FUN_1008_5D48 (release of a diagonal, 200 ms) */
	uint32_t pad_rel_due[2];
	uint8_t pad_kbd, pad_mouse; /* DAT_5B7A / DAT_5B7B: keyboard / mouse used by a controller */
	uint8_t pad_mouse_code;    /* DAT_48FC: last mouse direction */
	uint8_t joy_alt;           /* builtin 6E (DAT_5B7E): alternative joystick reading */
	uint8_t pad_joy;           /* DAT_5B79: a player uses a joystick */
	int joy_n;                 /* DAT_40D4 -> G(5016): joysticks found (0..2), set by the caller */
	uint8_t joy_ready[34];     /* DS:4905: zone ready to send its event (17 per joystick) */
	uint8_t joy_prev[2];       /* DS:4927: last direction zone of each joystick */
	/* builtins 8E / 91 / 97 / 9A: scripts as encoded constants (0 = none) and DAT_5B92 */
	uint16_t v150a;            /* DAT_150A: called with 1/0 when the window (de)activates */
	uint16_t v1546;            /* DAT_1546: rectangle-selection script (x1, y1, x2, y2) */
	uint16_t v1540;            /* DAT_1540: queued with the wave id when opcode 08 starts a wave */
	uint8_t v5b92;             /* DAT_5B92: Ctrl+Shift capture mode of the original (stored only) */
	uint8_t sel_on;            /* DAT_5B97: rectangle selection in progress */
	int16_t sel[4];            /* DS:07EC..07F2: x1, y1, x2, y2 of the selection */
	/* builtin 78 (S_075): window shake; provided by whoever owns the window, NULL = nothing */
	void (*shake)(struct Rt *rt, int dx, int dy);
	/* sprite world (SprWorld of sprite.c), created by whoever uses the runtime; NULL = no graphics */
	void *spr;
	/* diagnostics */
	FILE *trace;
	uint32_t unimpl_op[256], unimpl_builtin[256];
};

#define G(n) (rt->g[(n)])

/* ---- lifecycle */
int rt_init(Rt *rt, const char *datadir, FILE *trace);
void rt_shutdown(Rt *rt);
/* Opens the library (looks up the translated logic by file name) and runs script 0. */
int rt_open_library(Rt *rt, const char *file);
/* To be called on every tick of the main loop: timers and pending library changes. */
void rt_tick(Rt *rt, uint32_t now_ms);
void rt_report(const Rt *rt, FILE *out);

/* ---- calls between scripts */
/* Entry/exit of a script: checks nesting and stop. */
int rt_enter(Rt *rt, unsigned id);
void rt_leave(Rt *rt);
/* Runs script id (index entry) with the given frame. */
void rt_run(Rt *rt, unsigned id, int16_t *frame);
/* Calls script id as a function: copies the arguments into the frame, returns its return value. */
int16_t rt_call(Rt *rt, unsigned id, int16_t *frame, unsigned argc, const int16_t *args);
/* Runs entry item of list id (type 11). */
int rt_run_list(Rt *rt, unsigned id, int16_t *l, unsigned item);
unsigned rt_list_len(const Rt *rt, unsigned id);

/* Direct call from generated source: checks nesting and stop, then exits if needed. */
#define RT_CALL(fn, id, frame)                     \
	do {                                           \
		if (rt_enter(rt, (id))) {                  \
			fn(rt, (frame));                       \
			rt_leave(rt);                          \
		}                                          \
		if (rt->stop)                              \
			RT_END;                                \
	} while (0)

/* ---- instructions with known semantics */
int rt_load(Rt *rt, unsigned id);     /* 0x02 */
int rt_unload(Rt *rt, unsigned id);   /* 0x03 */
int rt_show(Rt *rt, unsigned sprite, unsigned anim, int hide_first); /* 0x05 */
void rt_link(Rt *rt, const char *file, int stop_audio, int ret); /* 0x12 */
void rt_quit(Rt *rt);                 /* 0x0D */
int rt_run_random(Rt *rt, int16_t *l, uint8_t *last, unsigned n, const uint16_t *ids); /* 0x16 */
int rt_run_next(Rt *rt, int16_t *l, uint8_t *last, unsigned n, const uint16_t *ids);   /* 0x17 */
int rt_run_random_list(Rt *rt, int16_t *l, uint8_t *last, unsigned list);            /* 0x16 list */
int rt_run_next_list(Rt *rt, int16_t *l, uint8_t *last, unsigned list);              /* 0x17 list */
int rt_run_index(Rt *rt, int16_t *l, unsigned list, int16_t *var, unsigned fallback,
	int run_fallback, int autoinc);   /* 0x22 */
void rt_debug(Rt *rt, unsigned str, int value); /* 0x1B */
void rt_set_mouse(Rt *rt, int x, int y);         /* 0x49 */
void rt_set_string(Rt *rt, const char *s);       /* 0x77 */
const char *rt_string(const Rt *rt, unsigned id);

/* Argument of rt_sprintf: numeric value or string id (opcode 0x38). */
typedef struct {
	uint8_t is_str;
	int16_t v;
} RtArg;

int rt_sprintf(Rt *rt, unsigned dest, unsigned fmt, unsigned argc, const RtArg *args); /* 0x38 */
/* INI (0x3B read, 0x3C write): key and section are string ids (section 0 = default);
 * enc = value encryption using the first character of the key (FUN_1008_AD7C/ADDC). */
void rt_ini_get_int(Rt *rt, int16_t *var, unsigned key, unsigned section, int enc);
void rt_ini_get_str(Rt *rt, unsigned str, unsigned key, unsigned section, int enc);
void rt_ini_put_int(Rt *rt, int value, unsigned key, unsigned section, int enc);
void rt_ini_put_str(Rt *rt, unsigned str, unsigned key, unsigned section, int enc);
void rt_cursor(Rt *rt, int mode);                    /* 0x1F */
void rt_fade(Rt *rt, int in, int speed);             /* 0x0A in, 0x0B out (1..100) */
/* 0x14: removes the timer with raw id (instruction word, like opcode 13); all = every timer */
void rt_stop_timer(Rt *rt, unsigned id, int all);
int rt_compare(int a, int b, unsigned op);           /* operators of 0x26 and 0x11 (1008:8C32) */

/* ---- input from the main loop (WndProc of TOPSY, 1008:ED3C). Coordinates relative to the center
 * of the screen (viewport origin, SetViewportOrgEx(w/2, h/2) in TOPSYS01). */
/* WM_KEYDOWN: vk = Windows virtual code; shift/ctrl = GetKeyState(VK_SHIFT/CONTROL) state */
void rt_key_down(Rt *rt, unsigned vk, int shift, int ctrl);
/* WM_CHAR (ANSI code, cp1252): goes to the active text field (FUN_1010_230C) */
void rt_char(Rt *rt, unsigned c);
/* Pause key (FUN_1008_3140): script DAT_150E with veto, or sound pause */
void rt_toggle_pause(Rt *rt);
/* Window activated or deactivated (WM_ACTIVATEAPP -> FUN_1008_E896) */
void rt_set_active(Rt *rt, int active);
/* 1 = the engine works on this tick (timers, queue, animations): DAT_5B8B && !DAT_5B85 */
int rt_running(const Rt *rt);
/* Engine keys in 7THLEVEL.INI (FUN_1000_05E4, FUN_1008_BF32, TOPSYA01 0CB8): once,
 * after setting resolution and ini_path, before the first library */
void rt_load_settings(Rt *rt);
void rt_key_up(Rt *rt, unsigned vk);       /* WM_KEYUP */
void rt_mouse_move(Rt *rt, int x, int y);  /* WM_MOUSEMOVE */
/* WM_xBUTTONDOWN / UP: button 1 = left, 2 = right */
void rt_mouse_button(Rt *rt, int x, int y, int button, int down);
/* Joystick (MM_JOY1MOVE/MM_JOY2MOVE, BUTTONDOWN/UP; TOPSY 1008:5AF4): joy 0/1, assi -32768..32767
 * relative to the center, buttons 0..3. */
void rt_joy_move(Rt *rt, int joy, int x, int y);
void rt_joy_button(Rt *rt, int joy, int button, int down);

/* Instruction whose handler is not ported yet: bytes = original instruction. */
int rt_op(Rt *rt, int16_t *l, const uint8_t *bytes);

/* ---- expressions */
int16_t rt_builtin(Rt *rt, unsigned id, unsigned argc, const int16_t *args);
unsigned rt_rand(Rt *rt);
/* Conversions between variable pointers and the 16-bit values that scripts store in them:
 * same numbering as the original DS (globals 0x154A + 2n, locals 0x4084 - 2k). */
int16_t rt_ptr2int(const Rt *rt, const int16_t *p);
int16_t *rt_int2ptr(Rt *rt, int16_t v);

/* Value of an encoded operand (only for rt_op handlers). */
int16_t rt_operand(Rt *rt, int16_t *l, uint16_t enc);

/* Expression operators / and % (Script_EvalExpr 0x15/0x16, 1008:2551): a zero divisor is the
 * runtime error 0x6F (rt_error) and the result is 0. */
int16_t rt_div(Rt *rt, int a, int b);
int16_t rt_mod(Rt *rt, int a, int b);
/* Runtime error (FUN_1010_2682): message, every script stops (DAT_1548 = code), the game closes. */
void rt_error(Rt *rt, unsigned code);

#endif
